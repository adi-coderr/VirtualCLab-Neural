export interface SeedAtom {
  element: string;
  x2d: number;
  y2d: number;
  x3d: number;
  y3d: number;
  z3d: number;
  formalCharge?: number;
}

export interface SeedBond {
  a: number;
  b: number;
  order: 1 | 2 | 3;
  type?: "covalent" | "ionic";
}

export interface SeedStructure {
  atoms: SeedAtom[];
  bonds: SeedBond[];
}

export interface SeedIon {
  formula: string;
  charge: number;
}

