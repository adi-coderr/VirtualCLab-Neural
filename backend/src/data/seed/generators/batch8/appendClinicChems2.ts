let fileContent = fs.readFileSync(targetFile, "utf8");

const chemsToAdd: any[] = [];
for (const chem of chems) {
  if (fileContent.includes(`"id": "${chem.id}"`)) {
    console.log(`Skipping already present chemical: ${chem.id}`);
  } else {
    chemsToAdd.push(chem);
  }
}

if (chemsToAdd.length > 0) {
  const lastIndex = fileContent.lastIndexOf("];");
  if (lastIndex === -1) {
    throw new Error("Could not find ending '];' in chemicalDefinitionsBatch8.ts");
  }

  const jsonEntries = chemsToAdd.map(c => "  " + JSON.stringify(c, null, 2).replace(/\n/g, "\n  ")).join(",\n");
  const updatedContent = fileContent.slice(0, lastIndex).trimEnd() + ",\n" + jsonEntries + "\n];\n";

  fs.writeFileSync(targetFile, updatedContent, "utf8");
  console.log(`✓ Added ${chemsToAdd.length} chemicals to chemicalDefinitionsBatch8.ts`);
} else {
  console.log("No new chemicals needed to be added.");
}
