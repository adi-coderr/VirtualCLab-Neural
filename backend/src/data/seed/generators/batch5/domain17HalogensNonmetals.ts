function normalizeReactionType(rawType?: string): any {
  switch (rawType) {
    case "condensation":
      return "synthesis";
    case "hydrolysis":
    case "substitution":
      return "double_displacement";
    case "dehydration":
      return "decomposition";
    default:
      return rawType || "redox_other";
  }
}

export function buildDomain17HalogensNonmetals(): void {
  for (const r of domain17RawReactions as any[]) {
    addReaction({
      id: r.id,
      name: r.name,
      reactionType: normalizeReactionType(r.reactionType),
      reactants: r.reactants,
      products: r.products,
      catalystChemicalId: r.catalystChemicalId,
      enthalpyKjPerMol: r.enthalpy,
      temperatureMinC: 20,
      temperatureMaxC: 600,
      observableEffects: [
        {
          type: "color_change",
          description: r.desc,
        }
      ],
      safetyNotes: "Halogens, interhalogens, and phosphorus/sulfur halides. Highly reactive, corrosive, and toxic oxidizers. Avoid contact with water or organic matter unless strictly controlled."
    });
  }
}
