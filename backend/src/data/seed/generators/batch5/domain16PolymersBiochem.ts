function normalizeReactionType(rawType?: string): any {
  switch (rawType) {
    case "condensation":
      return "synthesis";
    case "hydrolysis":
    case "substitution":
      return "double_displacement";
    case "dehydration":
      return "decomposition";
    default:
      return rawType || "synthesis";
  }
}

export function buildDomain16PolymersBiochem(): void {
  for (const r of domain16RawReactions as any[]) {
    addReaction({
      id: r.id,
      name: r.name,
      reactionType: normalizeReactionType(r.reactionType),
      reactants: r.reactants,
      products: r.products,
      catalystChemicalId: r.catalystChemicalId,
      enthalpyKjPerMol: r.enthalpy,
      temperatureMinC: 15,
      temperatureMaxC: 300,
      observableEffects: [
        {
          type: "color_change",
          description: r.desc,
        }
      ],
      safetyNotes: "Polymerization, biochemical and macromolecular processes. Handle reactive monomers, peroxides, and carboxylic anhydrides with proper ventilation and personal protective equipment."
    });
  }
}
